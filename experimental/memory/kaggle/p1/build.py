GUARD = '''

# ---------------------------------------------------------------- bundle integrity
#   shift_arms.Net and cpu_precheck.Net share a name; if concatenation shadowed one, the
#   transformer ceiling would silently be a ParityBlock and the gate would compare the
#   architecture against itself while every number still looked plausible.
assert RefNet is not ParityNet, 'BUNDLE BROKEN: the two Net classes were collapsed into one'
#   identity is necessary but not sufficient - check each actually builds the mixer it should.
#   (the first version of this line read `assert 'Attn' in ... or True`, a tautology that could
#   never fail. A vacuous assert is worse than none: it reads as coverage and provides none.)
_a = type(RefNet('transformer', 16, 64, 1).mix[0]).__name__
_b = type(ParityNet(16, 64, 1, head_dim=32, channel_gates=False, tied=True, n_read=2).mix[0]).__name__
assert _a == 'Attn', 'RefNet builds %s, not attention - the ceiling would be a ParityBlock' % _a
assert _b == 'ParityBlock', 'ParityNet builds %s, not ParityBlock' % _b
print('bundle integrity: RefNet mixer=%s  ParityNet mixer=%s  distinct=%s'
      % (_a, _b, RefNet is not ParityNet), flush=True)
del _a, _b

'''


def strip(text: str, drop_main: bool) -> str:
    if drop_main:
        text = re.split(r'^if __name__ ==', text, maxsplit=1, flags=re.M)[0]
    out = []
    for line in text.splitlines(keepends=True):
        s = line.strip()
        if s == FUTURE:
            continue
        if re.match(r'^\s*from\s+(%s)\s+import\s' % '|'.join(LOCAL), line):
            continue
        if re.match(r'^\s*import\s+(%s)\s*$' % '|'.join(LOCAL), line):
            continue
        out.append(line)
    return ''.join(out)


if __name__ == '__main__':
    import sys
    out, sets = OUT, []
    for a in sys.argv[1:]:
        if a.startswith('--dir='):
            out = pathlib.Path(a[len('--dir='):]).resolve() / out.name
        elif a.startswith('--name='):
            out = out.parent / (a[len('--name='):] + '.py')
        elif '=' in a:
            sets.append(tuple(a.split('=', 1)))
        else:
            raise SystemExit('unrecognised argument: %s' % a)
    assert PRELUDE.count('#@OVERRIDES@\n') == 1, 'override marker missing from PRELUDE'
    over = ''.join('os.environ.setdefault(%r, %r)\n' % kv for kv in sets)
    chunks, digests = [PRELUDE.replace('#@OVERRIDES@\n', over)], []
    for i, (name, aliases) in enumerate(MODULES):
        p = ROOT / name
        raw = p.read_bytes()
        digests.append((name, hashlib.sha256(raw).hexdigest()[:12]))
        body = strip(raw.decode('utf-8'), drop_main=(name != 'gpu_run.py'))
        chunks.append('\n# %s\n# --- from experiments/%s ---\n' % ('=' * 76, name))
        chunks.append(body)
        for a in aliases:
            chunks.append('\n%s\n' % a)
        if name == 'cpu_precheck.py':
            chunks.append(GUARD)
    out.write_text(''.join(chunks), encoding='utf-8')
    print('generated %s  (%d bytes)%s' % (out, out.stat().st_size,
                                          ''.join('  %s=%s' % kv for kv in sets)))
    for n, h in digests:
        print('  %-20s sha256 %s' % (n, h))

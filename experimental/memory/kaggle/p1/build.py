print('BUNDLE ENV  ' + '  '.join('%s=%s' % (k, os.environ.get(k, '-')) for k in (
    'MODE', 'STEPS', 'SEEDS', 'D', 'HEAD_DIM', 'NENT', 'DEPTHS', 'DMODE', 'RATIO', 'ARMS')), flush=True)

